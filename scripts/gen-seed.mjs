// Generates supabase/seed.sql from src/content/default-content.json.
// Usage: node scripts/gen-seed.mjs > supabase/seed.sql
import { readFileSync } from 'node:fs'

const c = JSON.parse(readFileSync(new URL('../src/content/default-content.json', import.meta.url)))
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const out = ['-- Generated by scripts/gen-seed.mjs — initial content (safe to re-run).', 'begin;']

c.series.forEach((s, i) =>
  out.push(`insert into series (id, code, name_fr, name_ar, position, active) values (${q(s.id)}, ${q(s.code)}, ${q(s.fr)}, ${q(s.ar)}, ${i}, ${s.active !== false}) on conflict (id) do update set code = excluded.code, name_fr = excluded.name_fr, name_ar = excluded.name_ar, position = excluded.position;`),
)
const subjects = new Map()
c.series.forEach((s) => s.subjects.forEach((x) => subjects.has(x.id) || subjects.set(x.id, x)))
subjects.forEach((x) => out.push(`insert into subjects (id, name_fr, name_ar) values (${q(x.id)}, ${q(x.fr)}, ${q(x.ar)}) on conflict (id) do nothing;`))

c.series.forEach((s) =>
  s.subjects.forEach((x, i) => {
    const p = c.programme[s.id]?.[x.id]
    // Per-série name only when it differs from the catalog name.
    const base = subjects.get(x.id)
    const nfr = x.fr !== base.fr ? x.fr : null
    const nar = x.ar !== base.ar ? x.ar : null
    out.push(`insert into serie_subjects (serie_id, subject_id, coeff, position, source, name_fr, name_ar) values (${q(s.id)}, ${q(x.id)}, ${x.coeff}, ${i}, ${q(p?.source ?? 'generic')}, ${q(nfr)}, ${q(nar)}) on conflict (serie_id, subject_id) do update set coeff = excluded.coeff, position = excluded.position, source = excluded.source, name_fr = excluded.name_fr, name_ar = excluded.name_ar;`)
    p?.chapters.forEach((ch, j) =>
      out.push(`insert into chapters (serie_id, subject_id, chapter_key, title_fr, title_ar, weeks, position) values (${q(s.id)}, ${q(x.id)}, ${q(ch.id)}, ${q(ch.fr)}, ${q(ch.ar)}, ${q(ch.weeks)}, ${j}) on conflict (serie_id, subject_id, chapter_key) do update set title_fr = excluded.title_fr, title_ar = excluded.title_ar, weeks = excluded.weeks, position = excluded.position;`),
    )
  }),
)
c.links.forEach((l, i) =>
  out.push(`insert into resources (title, url, category, description_fr, description_ar, serie_id, subject_id, position) select ${q(l.title)}, ${q(l.url)}, ${q(l.category)}, ${q(l.fr)}, ${q(l.ar)}, ${q(l.serie)}, ${q(l.subject)}, ${i} where not exists (select 1 from resources where url = ${q(l.url)});`),
)
out.push(`insert into app_config (key, value) values ('bac_date', ${q(JSON.stringify(c.bacDate))}::jsonb), ('content_version', '${c.version}'::jsonb) on conflict (key) do nothing;`)
out.push('commit;')
console.log(out.join('\n'))
